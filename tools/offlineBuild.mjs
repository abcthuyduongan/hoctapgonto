import { createHash } from 'node:crypto';
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { join, relative, resolve, sep } from 'node:path';
import {BROWSER_NOTICE_PACKAGES,thirdPartyNotices} from './thirdPartyNotices.mjs';

const CACHE_PREFIX = 'bao-an-learning-build-';

async function filesBelow(directory) {
  const result = [];
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const path = join(directory, entry.name);
    if (entry.isDirectory()) result.push(...await filesBelow(path));
    else if (entry.isFile() && entry.name !== 'sw.js') result.push(path);
  }
  return result;
}

/** Generate the worker after Vite has emitted every hashed lazy chunk and public asset. */
export async function writeOfflineWorker(outDir) {
  const directory = resolve(outDir);
  const files = (await filesBelow(directory)).sort();
  const manifest = [];
  for (const file of files) {
    const bytes = await readFile(file);
    manifest.push({
      url: `/${relative(directory, file).split(sep).join('/')}`,
      revision: createHash('sha256').update(bytes).digest('hex').slice(0, 16),
    });
  }
  if (!manifest.some(entry => entry.url === '/index.html')) throw new Error('Offline build requires index.html.');
  const buildId = createHash('sha256').update(JSON.stringify(manifest)).digest('hex').slice(0, 16);
  const urls = [...new Set(['/', ...manifest.map(entry => entry.url)])];
  const source = `/** Generated by tools/offlineBuild.mjs. */
const CACHE_PREFIX=${JSON.stringify(CACHE_PREFIX)};
const BUILD_ID=${JSON.stringify(buildId)};
const CACHE_NAME=CACHE_PREFIX+BUILD_ID;
const PRECACHE_URLS=${JSON.stringify(urls)};
const PREVIOUS_BUILDS_TO_KEEP=2;

function isOwnedBuildCache(name){
  return name.startsWith(CACHE_PREFIX)&&/^[a-f0-9]{16}$/.test(name.slice(CACHE_PREFIX.length));
}
async function previousBuildCaches(){
  // CacheStorage lists caches in creation order; retain two earlier deployments for old tabs.
  return (await caches.keys()).filter(name=>isOwnedBuildCache(name)&&name!==CACHE_NAME);
}
async function pruneBuildCaches(){
  const previous=await previousBuildCaches();
  for(const name of previous.slice(0,Math.max(0,previous.length-PREVIOUS_BUILDS_TO_KEEP)))await caches.delete(name);
}

async function notify(message){
  const clients=await self.clients.matchAll({type:'window',includeUncontrolled:true});
  clients.forEach(client=>client.postMessage(message));
}
async function matchOwned(request){
  const current=await caches.open(CACHE_NAME);
  const direct=await current.match(request,{ignoreSearch:false}) || await current.match(new URL(request.url).pathname);
  if(direct)return direct;
  const names=(await previousBuildCaches()).slice(-PREVIOUS_BUILDS_TO_KEEP).reverse();
  for(const name of names){const found=await (await caches.open(name)).match(request,{ignoreSearch:false});if(found)return found;}
}
self.addEventListener('install',event=>{
  event.waitUntil((async()=>{
    const cache=await caches.open(CACHE_NAME);
    for(const url of PRECACHE_URLS){
      const response=await fetch(new Request(url,{cache:'reload'}));
      if(!response.ok)throw new Error('Precache failed: '+url+' ('+response.status+')');
      await cache.put(url,response);
    }
    await notify({type:'OFFLINE_READY',buildId:BUILD_ID});
  })());
});
self.addEventListener('activate',event=>event.waitUntil((async()=>{
  await pruneBuildCaches();
  await self.clients.claim();
  await notify({type:'OFFLINE_READY',buildId:BUILD_ID});
})()));
self.addEventListener('message',event=>{
  if(event.data?.type==='GET_OFFLINE_STATUS')event.source?.postMessage({type:'OFFLINE_READY',buildId:BUILD_ID});
  if(event.data?.type==='SKIP_WAITING')self.skipWaiting();
});
self.addEventListener('fetch',event=>{
  const request=event.request;
  if(request.method!=='GET')return;
  const url=new URL(request.url);
  if(url.origin!==self.location.origin)return;
  // Authenticated classroom data must always reach the server, never a build cache.
  if(url.pathname.startsWith('/api/'))return;
  if(request.mode==='navigate'){
    event.respondWith((async()=>{
      try{
        const response=await fetch(request);
        if(response.ok){const cache=await caches.open(CACHE_NAME);event.waitUntil(cache.put('/index.html',response.clone()));}
        return response;
      }catch{
        return (await (await caches.open(CACHE_NAME)).match('/index.html')) || (await matchOwned(new Request(new URL('/index.html',self.location.origin))));
      }
    })());
    return;
  }
  event.respondWith((async()=>{
    const cached=await matchOwned(request);
    if(cached)return cached;
    const response=await fetch(request);
    if(response?.ok&&response.type==='basic')event.waitUntil((await caches.open(CACHE_NAME)).put(request,response.clone()));
    return response;
  })());
});
`;
  await writeFile(join(directory, 'sw.js'), source, 'utf8');
  return { buildId, cacheName: `${CACHE_PREFIX}${buildId}`, manifest };
}

export function offlineBuildPlugin() {
  let outDir;
  return {
    name: 'bao-an-offline-build',
    apply: 'build',
    configResolved(config) { outDir = resolve(config.root, config.build.outDir); },
    async closeBundle() {
      await writeFile(join(outDir,'THIRD_PARTY_NOTICES.txt'),await thirdPartyNotices({packageNames:BROWSER_NOTICE_PACKAGES}));
      await writeOfflineWorker(outDir);
    },
  };
}
