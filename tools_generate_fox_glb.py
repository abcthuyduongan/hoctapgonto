"""Create a self-authored stylized fox guide GLB for pipeline smoke testing.
This model is NOT the final premium mascot; no rig, animations or textures.
License: OWNED (generated by the project, no external meshes/assets).
"""
from pathlib import Path
import numpy as np
import trimesh
from trimesh.visual.material import PBRMaterial
from trimesh.visual import TextureVisuals
from trimesh.transformations import rotation_matrix

ROOT=Path(__file__).resolve().parent
OUT=ROOT/'public/models/fox-guide-prototype.glb'
scene=trimesh.Scene()
parts=0

def add(mesh,color,name):
    global parts
    rgba=list(bytes.fromhex(color.lstrip('#'))) + [255]
    mesh.visual=TextureVisuals(material=PBRMaterial(name=name,baseColorFactor=rgba,metallicFactor=0.0,roughnessFactor=.69,doubleSided=True))
    scene.add_geometry(mesh,geom_name=f'{parts:03d}_{name}')
    parts+=1

def egg(center,radii,color,name,sub=2,rot=None):
    obj=trimesh.creation.icosphere(subdivisions=sub,radius=1)
    obj.vertices*=np.array(radii)
    if rot:
        axis,angle=rot
        obj.apply_transform(rotation_matrix(angle,axis))
    obj.apply_translation(center)
    add(obj,color,name)

def stick(start,end,rad,color,name,sections=12):
    v=np.array(end,dtype=float)-np.array(start,dtype=float)
    obj=trimesh.creation.cylinder(radius=rad,height=np.linalg.norm(v),sections=sections)
    obj.apply_transform(trimesh.geometry.align_vectors([0,0,1],v))
    obj.apply_translation((np.array(start)+np.array(end))/2)
    add(obj,color,name)

def fin(base,tip,radius,color,name):
    vec=np.array(tip,dtype=float)-np.array(base,dtype=float)
    c=trimesh.creation.cone(radius=radius,height=np.linalg.norm(vec),sections=12)
    c.apply_transform(trimesh.geometry.align_vectors([0,0,1],vec))
    c.apply_translation(base)
    add(c,color,name)

# Legs and feet
for s in (-1,1):
    egg((s*.31,.30,.05),(.23,.37,.25),'#ea874b','leg',2)
    egg((s*.31,.12,.28),(.27,.15,.37),'#fff2dc','boot',2)
# Teal explorer jumpsuit and warm tummy
egg((0,.88,0),(.49,.64,.38),'#147bb4','outfit',3)
egg((0,1.06,.33),(.32,.33,.085),'#ffe4ad','bib',2)
egg((0,1.26,.0),(.28,.16,.31),'#227bc4','collar',2)
# Hands, waving paw
for s in (-1,1):
    if s<0:
        start,end=(s*.42,1.16,.1),(s*.73,.96,.2)
    else:
        start,end=(s*.42,1.18,.07),(s*.76,1.63,.34)
    stick(start,end,.17,'#e77a3c','arms')
    egg(end,(.19,.19,.16),'#fff1d3','paw',2)
# Main face and cheek fluff
egg((0,1.86,.04),(.69,.66,.59),'#ef8d48','fox_head',3)
for s in (-1,1):
    egg((s*.43,1.6,.43),(.32,.28,.20),'#fff3df','cheek',2)
    fin((s*.47,2.23,0.02),(s*.50,2.87,-.02),.30,'#ed803e','pointed_ear')
    fin((s*.49,2.32,.205),(s*.49,2.72,.21),.16,'#f7ac91','inner_ear')
    egg((s*.24,2.00,.55),(.185,.25,.115),'#fff8ed','eye_white',2)
    egg((s*.22,2.00,.658),(.087,.155,.043),'#1f2b4a','eye_iris',2)
    egg((s*.19,2.09,.702),(.043,.062,.014),'#ffffff','eyeshine',1)
    egg((s*.29,1.73,.55),(.20,.14,.11),'#fff0dc','muzzle_side',2)
# Snout and mouth
egg((0,1.70,.61),(.21,.16,.2),'#ffe6cb','muzzle',2)
egg((0,1.75,.78),(.12,.085,.087),'#312a34','nose',2)
for s in (-1,1):
    stick((0,1.61,.793),(s*.13,1.56,.748),.019,'#502e35','smile_line',8)
# Backpack and straps
egg((0,.95,-.41),(.46,.54,.2),'#edba4f','backpack',2)
for s in (-1,1):
    stick((s*.35,1.34,.31),(s*.34,.66,.30),.060,'#ffce72','strap',9)
# Tail, arcing out left behind the fox
egg((-.52,.76,-.58),(.43,.28,.42),'#e7763c','tail_base',2)
egg((-.91,.86,-.68),(.50,.32,.37),'#f18a45','tail_mid',2)
egg((-1.21,1.00,-.60),(.30,.27,.31),'#fff6dc','tail_tip',2)
# Tiny chest star, can be distinctly recognized even at a distance
star = trimesh.creation.icosphere(subdivisions=1,radius=1)
star.vertices *= np.array([.18,.19,.075]);star.apply_translation([0,.84,.39])
add(star,'#ffe15a','star_badge')
OUT.parent.mkdir(parents=True,exist_ok=True)
